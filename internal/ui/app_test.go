func TestDevicesTab(t *testing.T) {
	a := newTestApp(t, fixtureRoot, 120, 40)
	if err := a.press(t, ']'); err != nil {
		t.Fatal(err)
	}
	devices := a.viewText(t, viewModules)
	assertContains(t, "devices", devices, "c2:00.0", "Krackan [Radeon", "amdgpu", "amdxdna?", "usb 1-1", "Integrated Cam", "uvcvideo", "snd_hda_intel")
	assertContains(t, "bar", a.viewText(t, viewOptions), "Go to module: enter")
	assertNotContains(t, "bar", a.viewText(t, viewOptions), "All modules: A")

	// Unbound NPU: candidates from modules.alias and the resolve-alias command.
	a.devs.selectKey("pci0000:c3:00.1")
	a.syncModulesSelection()
	a.renderDetails()
	assertContains(t, "details", a.viewText(t, viewDetails), "none bound", "amdxdna (from modules.alias)",
		"$ modprobe --resolve-alias", "pci:v00001022d000017F0sv000017AAsd00003820bc11sc80i00")

	// Enter on an unbound device whose module is not loaded switches to "all".
	if err := a.press(t, gocui.KeyEnter); err != nil {
		t.Fatal(err)
	}
	if a.tab != tabModules || !a.showAll {
		t.Fatalf("tab=%d showAll=%v, want modules tab with all modules", a.tab, a.showAll)
	}
	if e, _ := a.mods.selected(); e.Name != "amdxdna" {
		t.Errorf("selected %q, want amdxdna", e.Name)
	}

	// USB device details list each interface.
	if err := a.press(t, ']'); err != nil {
		t.Fatal(err)
	}
	a.devs.selectKey("usb1-1")
	a.renderDetails()
	assertContains(t, "usb details", a.viewText(t, viewDetails),
		"1-1:1.0  Video     uvcvideo (loaded)", "1-1:1.4  class fe  none bound", "usb:v174Fp1826d1010dcEFdsc02dp01icFEisc01ip01in04",
		"$ lsusb -d 174f:1826")
}

func TestHelpPopup(t *testing.T) {
	a := newTestApp(t, fixtureRoot, 120, 40)
	if err := a.press(t, '?'); err != nil {
		t.Fatal(err)
	}
	if a.currentView() != viewHelp {
		t.Fatalf("focus = %q, want help", a.currentView())
	}
	assertContains(t, "help", a.viewText(t, viewHelp), "Global", "Focus Status", "Toggle loaded / all modules", "Filter prompt")
	// Global keys are inert while the popup is open; q closes it.
	if err := a.press(t, '1'); err != nil {
		t.Fatal(err)
	}
	if a.currentView() != viewHelp {
		t.Fatalf("'1' moved focus to %q while help was open", a.currentView())
	}
	if err := a.press(t, 'q'); err != nil {
		t.Fatalf("q in help should close it, got %v", err)
	}
	if a.currentView() != viewModules {
		t.Errorf("focus = %q, want modules", a.currentView())
	}
	if err := a.press(t, 'q'); !errors.Is(err, gocui.ErrQuit) {
		t.Errorf("q outside help = %v, want ErrQuit", err)
	}

	// Closing help returns to the view it was opened from, not the left panel.
	for _, key := range []any{'0', '?', gocui.KeyEsc} {
		if err := a.press(t, key); err != nil {
			t.Fatal(err)
		}
	}
	if a.currentView() != viewDetails {
		t.Errorf("focus after closing help = %q, want details", a.currentView())
	}
}

