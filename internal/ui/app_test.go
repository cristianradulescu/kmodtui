func TestFilter(t *testing.T) {
	a := newTestApp(t, fixtureRoot, 120, 40)
	if err := a.press(t, '/'); err != nil {
		t.Fatal(err)
	}
	if a.currentView() != viewFilter {
		t.Fatalf("focus = %q, want filter", a.currentView())
	}
	a.typeText(t, "nvme-c")
	// "nvme-c" is normalized to "nvme_c": only nvme_core matches.
	assertContains(t, "screen", a.screen(), "Filter: nvme-c", "filter: nvme-c · 1 of 1", "[2]─Modules - Devices")
	assertContains(t, "modules", a.viewText(t, viewModules), "nvme_core")
	assertNotContains(t, "modules", a.viewText(t, viewModules), "amdgpu", "nvme_auth")

	// Enter keeps the filter; Esc in the list clears it.
	if err := a.press(t, gocui.KeyEnter); err != nil {
		t.Fatal(err)
	}
	if a.currentView() != viewModules {
		t.Fatalf("focus = %q, want modules", a.currentView())
	}
	assertContains(t, "screen", a.screen(), "filter: nvme-c", "Clear filter: esc")
	if err := a.press(t, gocui.KeyEsc); err != nil {
		t.Fatal(err)
	}
	assertContains(t, "screen", a.screen(), "of 28")
	assertNotContains(t, "screen", a.screen(), "filter:")

	// Esc in the prompt cancels.
	if err := a.press(t, '/'); err != nil {
		t.Fatal(err)
	}
	a.typeText(t, "zzz")
	assertContains(t, "modules", a.viewText(t, viewModules), "No modules match the filter")
	if err := a.press(t, gocui.KeyEsc); err != nil {
		t.Fatal(err)
	}
	assertContains(t, "screen", a.screen(), "1 of 28")
}

