// The kmod fixtures double as UI fixtures.
const (
	fixtureRoot    = "../kmod/testdata/root"
	fixtureModinfo = "../kmod/testdata/modinfo"
)

// fixtureRunner answers modinfo from the kmod fixtures; anything else
// behaves like a missing binary.
type fixtureRunner struct{}

func (fixtureRunner) Run(name string, args ...string) ([]byte, error) {
	if name == "modinfo" && len(args) > 0 {
		mod := args[len(args)-1]
		b, err := os.ReadFile(filepath.Join(fixtureModinfo, mod+".txt"))
		if err != nil {
			return nil, fmt.Errorf("modinfo: exit status 1: modinfo: ERROR: Module %s not found.", mod)
		}
		return b, nil
	}
	return nil, &exec.Error{Name: name, Err: exec.ErrNotFound}
}

// newTestApp renders the app headlessly. gocui keeps the screen in a package
// global, so these tests must not run in parallel.
func newTestApp(t *testing.T, root string, w, h int) *App {
	t.Helper()
	g, err := gocui.NewGui(gocui.NewGuiOpts{OutputMode: gocui.OutputTrue, Headless: true, Width: w, Height: h})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(g.Close)
	a := New(&kmod.Source{Root: root, Runner: fixtureRunner{}})
	a.background = func(work func() func()) { work()() }
	if err := a.init(g); err != nil {
		t.Fatal(err)
	}
	a.redraw(t)
	return a
}

func (a *App) redraw(t *testing.T) {
	t.Helper()
	if err := a.g.ForceLayoutAndRedraw(); err != nil {
		t.Fatal(err)
	}
}

// press dispatches a key through the binding table the way gocui does:
// bindings of the focused view first, then global ones.
func (a *App) press(t *testing.T, key any) error {
	t.Helper()
	cur := a.currentView()
	for _, global := range []bool{false, true} {
		for _, b := range a.bindings {
			if (b.views == nil) != global || !slices.Contains(b.keys, key) {
				continue
			}
			if !global && !slices.Contains(b.views, cur) {
				continue
			}
			err := a.wrap(b)(a.g, a.g.CurrentView())
			if errors.Is(err, gocui.ErrKeybindingNotHandled) {
				continue
			}
			a.redraw(t)
			return err
		}
	}
	a.redraw(t)
	return nil
}

// typeText feeds runes to the focused editable view through its editor.
func (a *App) typeText(t *testing.T, s string) {
	t.Helper()
	v := a.g.CurrentView()
	for _, ch := range s {
		v.Editor.Edit(v, 0, ch, gocui.ModNone)
	}
	a.redraw(t)
}

func (a *App) screen() string { return a.g.Snapshot() }

func (a *App) viewText(t *testing.T, name string) string {
	t.Helper()
	v, err := a.g.View(name)
	if err != nil {
		t.Fatalf("view %s: %v", name, err)
	}
	return v.Buffer()
}

// logText is the command log before wrapping.
func (a *App) logText() string { return stripSGR(strings.Join(a.logLines, "\n")) }

// flat collapses whitespace so assertions survive word wrapping.
func flat(s string) string { return strings.Join(strings.Fields(s), " ") }

func assertContains(t *testing.T, what, text string, wants ...string) {
	t.Helper()
	for _, w := range wants {
		if !strings.Contains(flat(text), flat(w)) {
			t.Errorf("%s: missing %q in:\n%s", what, w, text)
		}
	}
}

func assertNotContains(t *testing.T, what, text string, unwanted ...string) {
	t.Helper()
	for _, w := range unwanted {
		if strings.Contains(flat(text), flat(w)) {
			t.Errorf("%s: unexpected %q in:\n%s", what, w, text)
		}
	}
}

func TestStartupScreen(t *testing.T) {
	for _, size := range [][2]int{{80, 24}, {120, 40}, {200, 60}} {
		t.Run(fmt.Sprintf("%dx%d", size[0], size[1]), func(t *testing.T) {
			a := newTestApp(t, fixtureRoot, size[0], size[1])
			screen := a.screen()
			assertContains(t, "screen", screen,
				"[1]─Status", "[2]─Modules - Devices", "[3]─Boot config", "[4]─Changes", "[0]─Details", "Command log",
				"7.0.0-38-generic", "disabled (setup mode)", "OE (12288)",
				"amdgpu", "1 of 28",
				"╭", "╯",
				"Filter: /",
			)
			if a.currentView() != viewModules {
				t.Errorf("focus = %q, want modules", a.currentView())
			}
			// Details of the first module, with modinfo loaded.
			assertContains(t, "details", a.viewText(t, viewDetails),
				"amdgpu", "AMD GPU", "signed by Build time autogenerated kernel key", "pci c2:00.0", "Parameters (97)",
				"aspm", "= -1", "$ modinfo amdgpu")
			assertContains(t, "log", a.logText(),
				"$ uname -r", "$ lsmod  # List loaded modules", "$ lspci -nnk", "$ modinfo amdgpu")
		})
	}
}

func TestEmptyRootShowsErrors(t *testing.T) {
	a := newTestApp(t, t.TempDir(), 120, 40)
	assertContains(t, "modules", a.viewText(t, viewModules), "Cannot list modules", "no such file or directory")
	assertContains(t, "status", a.viewText(t, viewStatus), "Kernel      unknown", "not supported", "Taint       unknown")
	assertContains(t, "boot", a.viewText(t, viewBoot), "No entries managed by kmodtui")
	assertContains(t, "log", a.logText(), "/proc/modules: no such file or directory")
	if err := a.press(t, ']'); err != nil {
		t.Fatal(err)
	}
	assertContains(t, "devices", a.viewText(t, viewModules), "Cannot list devices")
	if err := a.press(t, '1'); err != nil {
		t.Fatal(err)
	}
	assertContains(t, "status details", a.viewText(t, viewDetails), "no such file or directory")
}

func TestNavigationAndFocus(t *testing.T) {
	a := newTestApp(t, fixtureRoot, 120, 40)
	if err := a.press(t, 'j'); err != nil {
		t.Fatal(err)
	}
	assertContains(t, "screen", a.screen(), "2 of 28")
	assertContains(t, "details", a.viewText(t, viewDetails), "amdxcp")

	if err := a.press(t, 'G'); err != nil {
		t.Fatal(err)
	}
	assertContains(t, "screen", a.screen(), "28 of 28")
	assertContains(t, "details", a.viewText(t, viewDetails), "videobuf2_common", "modinfo: exit status 1")
	if err := a.press(t, 'g'); err != nil {
		t.Fatal(err)
	}
	assertContains(t, "screen", a.screen(), "1 of 28")

	// Out-of-tree, unsigned, tainting module.
	a.mods.selectKey("vboxdrv")
	a.syncModulesSelection()
	a.renderDetails()
	assertContains(t, "details", a.viewText(t, viewDetails), "vboxdrv", "unsigned", "out-of-tree", "Taint        OE",
		"Used by      vboxnetadp, vboxnetflt", "Needed by    2, any depth: vboxnetadp, vboxnetflt")
	assertContains(t, "modules", a.viewText(t, viewModules), "vboxdrv OE")

	tests := []struct {
		key     any
		focus   string
		details string
	}{
		{'1', viewStatus, "Tainted by"},
		{'3', viewBoot, "blacklist pcspkr"},
		{'4', viewChanges, "No pending changes"},
		{'0', viewDetails, "No pending changes"}, // Details keeps the last left panel
		{gocui.KeyTab, viewLog, "No pending changes"},
		{gocui.KeyTab, viewStatus, "Tainted by"},
		{gocui.KeyBacktab, viewLog, "Tainted by"},
		{'2', viewModules, "vboxdrv"},
	}
	for _, tt := range tests {
		if err := a.press(t, tt.key); err != nil {
			t.Fatal(err)
		}
		if a.currentView() != tt.focus {
			t.Fatalf("after %v: focus = %q, want %q", tt.key, a.currentView(), tt.focus)
		}
		assertContains(t, fmt.Sprintf("details after %v", tt.key), a.viewText(t, viewDetails), tt.details)
	}
}

