func TestParseModinfo(t *testing.T) {
	tests := []struct {
		file        string
		name        string
		filename    string
		description string
		license     string
		signer      string
		builtin     bool
		signed      bool
		depends     []string
		aliases     int
		params      int
		firstParam  ParamInfo
	}{
		{
			file:        "nvme",
			name:        "nvme",
			filename:    "/lib/modules/7.0.0-38-generic/kernel/drivers/nvme/host/nvme.ko.zst",
			description: "NVMe host PCIe transport driver",
			license:     "GPL",
			signer:      "Build time autogenerated kernel key",
			signed:      true,
			depends:     []string{"nvme_core"},
			aliases:     77,
			params:      9,
			firstParam:  ParamInfo{Name: "use_threaded_interrupts", Type: "int"},
		},
		{
			file:        "amdgpu",
			name:        "amdgpu",
			filename:    "/lib/modules/7.0.0-38-generic/kernel/drivers/gpu/drm/amd/amdgpu/amdgpu.ko.zst",
			description: "AMD GPU",
			license:     "GPL and additional rights",
			signer:      "Build time autogenerated kernel key",
			signed:      true,
			depends: []string{"drm_display_helper", "amdxcp", "gpu_sched", "drm_buddy", "ttm", "cec",
				"drm_suballoc_helper", "drm_exec", "video", "drm_ttm_helper", "i2c_algo_bit", "drm_panel_backlight_quirks"},
			aliases:    3,
			params:     97,
			firstParam: ParamInfo{Name: "vramlimit", Desc: "Restrict VRAM for testing, in megabytes", Type: "int"},
		},
		{
			file:        "xhci_hcd",
			name:        "xhci_hcd",
			filename:    "(builtin)",
			description: "'eXtensible' Host Controller (xHC) Driver",
			license:     "GPL",
			builtin:     true,
			params:      2,
			firstParam:  ParamInfo{Name: "link_quirk", Desc: "Don't clear the chain bit on a link TRB", Type: "int"},
		},
		{
			file:        "uvcvideo",
			name:        "uvcvideo",
			filename:    "/lib/modules/7.0.0-38-generic/kernel/drivers/media/usb/uvc/uvcvideo.ko.zst",
			description: "USB Video Class driver",
			license:     "GPL",
			signer:      "Build time autogenerated kernel key",
			signed:      true,
			depends:     []string{"videodev", "videobuf2_v4l2", "mc", "uvc", "videobuf2_common", "videobuf2_vmalloc"},
			aliases:     4,
			params:      6,
			firstParam:  ParamInfo{Name: "clock", Desc: "Video buffers timestamp clock"},
		},
		{
			file:        "vboxdrv",
			name:        "vboxdrv",
			filename:    "/lib/modules/7.0.0-38-generic/updates/dkms/vboxdrv.ko.zst",
			description: "Oracle VirtualBox Support Driver",
			license:     "GPL",
			params:      2,
			firstParam:  ParamInfo{Name: "force_async_tsc", Desc: "force the asynchronous TSC mode", Type: "int"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.file, func(t *testing.T) {
			b, err := os.ReadFile(filepath.Join("testdata", "modinfo", tt.file+".txt"))
			if err != nil {
				t.Fatal(err)
			}
			mi := ParseModinfo(string(b))
			assertEqual(t, "name", mi.Get("name"), tt.name)
			assertEqual(t, "filename", mi.Get("filename"), tt.filename)
			assertEqual(t, "description", mi.Get("description"), tt.description)
			assertEqual(t, "license", mi.Get("license"), tt.license)
			assertEqual(t, "signer", mi.Get("signer"), tt.signer)
			assertEqual(t, "builtin", mi.Builtin(), tt.builtin)
			assertEqual(t, "signed", mi.Signed(), tt.signed)
			assertEqual(t, "depends", mi.Depends(), tt.depends)
			assertEqual(t, "aliases", len(mi.All("alias")), tt.aliases)
			assertEqual(t, "params", len(mi.Params), tt.params)
			if len(mi.Params) > 0 {
				assertEqual(t, "first param", mi.Params[0], tt.firstParam)
			}
		})
	}
}

func TestParseModinfoContinuationAndRepeats(t *testing.T) {
	b, err := os.ReadFile("testdata/modinfo/nvme.txt")
	if err != nil {
		t.Fatal(err)
	}
	mi := ParseModinfo(string(b))
	sig := mi.Get("signature")
	if lines := strings.Split(sig, "\n"); len(lines) != 26 || !strings.HasPrefix(lines[1], "37:0E:69:88") {
		t.Errorf("signature: got %d lines, second %q", len(lines), lines[1])
	}
	// Built-in modules can repeat keys (one set per compilation unit).
	b, err = os.ReadFile("testdata/modinfo/xhci_hcd.txt")
	if err != nil {
		t.Fatal(err)
	}
	mi = ParseModinfo(string(b))
	assertEqual(t, "descriptions", mi.All("description"), []string{
		"'eXtensible' Host Controller (xHC) Driver",
		"xHCI sideband driver for secondary interrupter management",
	})
}

func TestParseParm(t *testing.T) {
	tests := []struct {
		in   string
		want ParamInfo
	}{
		{"aspm:ASPM support (1 = enable, 0 = disable, -1 = auto) (int)", ParamInfo{"aspm", "ASPM support (1 = enable, 0 = disable, -1 = auto)", "int"}},
		{"use_threaded_interrupts:int", ParamInfo{Name: "use_threaded_interrupts", Type: "int"}},
		{"io_queue_depth:set io queue depth, should >= 2 and < 4096", ParamInfo{Name: "io_queue_depth", Desc: "set io queue depth, should >= 2 and < 4096"}},
		{"quirks:Enable/disable NVMe quirks by specifying quirks=VID:DID:quirk_names", ParamInfo{Name: "quirks", Desc: "Enable/disable NVMe quirks by specifying quirks=VID:DID:quirk_names"}},
		{"lockup_timeout:GPU lockup timeout in ms (default: 2000) (string)", ParamInfo{"lockup_timeout", "GPU lockup timeout in ms (default: 2000)", "string"}},
		{"ids:PCI IDs to handle (array of uint)", ParamInfo{"ids", "PCI IDs to handle", "array of uint"}},
		{"mode:Mode (see docs)", ParamInfo{Name: "mode", Desc: "Mode (see docs)"}},
		{"noacpi:disable acpi bios quirks (bool)", ParamInfo{"noacpi", "disable acpi bios quirks", "bool"}},
	}
	for _, tt := range tests {
		t.Run(tt.in, func(t *testing.T) {
			assertEqual(t, "param", parseParm(tt.in), tt.want)
		})
	}
}

func TestSourceModinfo(t *testing.T) {
	src, runner := fixtureSource(t)
	mi, op := src.Modinfo("nvme", "7.0.0-38-generic")
	if op.Err != nil {
		t.Fatal(op.Err)
	}
	assertEqual(t, "cmd", op.Cmd, "modinfo nvme")
	assertEqual(t, "description", mi.Get("description"), "NVMe host PCIe transport driver")
	// A fixture root must not make modinfo look at the live /lib/modules.
	assertEqual(t, "call", runner.calls[0], "modinfo -b testdata/root -k 7.0.0-38-generic nvme")

	_, op = src.Modinfo("nosuchmod", "7.0.0-38-generic")
	if op.Err == nil || !strings.Contains(op.Err.Error(), "not found") {
		t.Errorf("err = %v, want not found", op.Err)
	}
}
